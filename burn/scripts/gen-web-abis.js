// Writes web/src/generated/wellsAbi.ts from the compiled Well, credit line, oracle and position contracts, so the site
// always uses their exact ABIs (and can name their errors). Run after `npx hardhat compile`.
const fs = require("fs");
const path = require("path");

const ART = path.join(__dirname, "..", "artifacts", "src");
const OUT = path.join(__dirname, "..", "..", "web", "src", "generated", "wellsAbi.ts");
const list = [
  ["wellAbi", "WellTakestock.sol/WellTakestock.json"],
  ["creditDeskAbi", "CreditDeskTakestock.sol/CreditDeskTakestock.json"],
  ["oracleAbi", "OracleTakestock.sol/OracleTakestock.json"],
  ["positionAbi", "v4/PositionTakestock.sol/PositionTakestock.json"],
];
let ts = "// Generated by burn/scripts/gen-web-abis.js from burn/artifacts. Do not edit.\n";
for (const [name, file] of list) {
  const { abi } = JSON.parse(fs.readFileSync(path.join(ART, file), "utf8"));
  ts += `\nexport const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
fs.writeFileSync(OUT, ts);
console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
