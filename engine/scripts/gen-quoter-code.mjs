// Embeds the compiled QuoterTakestock creation code so the app can quote before the quoter is deployed
// (a "deployless" eth_call runs it in place). Run after `forge build` in ../contracts.
import { readFileSync, writeFileSync } from "node:fs";
const art = JSON.parse(readFileSync(new URL("../../contracts/out/QuoterTakestock.sol/QuoterTakestock.json", import.meta.url), "utf8"));
const code = art.bytecode.object;
writeFileSync(
  new URL("../src/quoterCode.ts", import.meta.url),
  `// Generated by scripts/gen-quoter-code.mjs from contracts/out. Do not edit.\nexport const QUOTER_CREATION_CODE = "${code}" as const;\n`,
);
console.log(`quoterCode.ts written (${(code.length - 2) / 2} bytes)`);
