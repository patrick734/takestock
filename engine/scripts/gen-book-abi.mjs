// Writes src/bookAbi.ts from the compiled BookTakestock, so the app and the keeper always use the exact ABI.
// Run after `forge build` in ../contracts.
import { readFileSync, writeFileSync } from "node:fs";
const art = JSON.parse(readFileSync(new URL("../../contracts/out/BookTakestock.sol/BookTakestock.json", import.meta.url), "utf8"));
writeFileSync(
  new URL("../src/bookAbi.ts", import.meta.url),
  `// Generated by scripts/gen-book-abi.mjs from contracts/out. Do not edit.\nexport const bookAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`,
);
console.log(`bookAbi.ts written (${art.abi.length} entries)`);
